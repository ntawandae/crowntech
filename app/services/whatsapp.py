"""
Sending quotations and receipts on WhatsApp (Meta WhatsApp Business Cloud API).

The PDF is generated by the app and uploaded straight to WhatsApp, so nobody has to download it first.

* Configured (WHATSAPP_TOKEN + WHATSAPP_PHONE_NUMBER_ID set): the PDF goes to the customer's WhatsApp
  automatically, as an approved template message with the PDF attached. A template is needed because WhatsApp
  only allows free-form messages to customers who wrote to the business in the last 24 hours.
* Not configured: the app falls back to a "click to chat" link, which opens WhatsApp with the customer's number
  and the message (with a secure PDF link) already filled in, so the cashier only has to press Send.

Failures never raise into a page: every function returns (ok, message).
"""
import logging
import re

import requests

log = logging.getLogger(__name__)

GRAPH = "https://graph.facebook.com"


# ---------------------------------------------------------------- configuration
def enabled(cfg):
    return bool(cfg.get("WHATSAPP_TOKEN") and cfg.get("WHATSAPP_PHONE_NUMBER_ID"))


def template_for(cfg, kind):
    """Approved template name for 'q' (quotation) or 'r' (receipt); '' means send a plain document message."""
    return (cfg.get("WHATSAPP_TEMPLATE_QUOTATION") if kind == "q" else cfg.get("WHATSAPP_TEMPLATE_RECEIPT")) or ""


# ---------------------------------------------------------------- phone numbers
def normalize_phone(raw, default_country="263"):
    """
    Customer number as WhatsApp wants it: international format, digits only.
    '0772 123 456' -> '263772123456'; '+263 77 212 3456' -> '263772123456'; '00263...' -> '263...'.
    Returns '' when it cannot be a real number.
    """
    digits = re.sub(r"\D", "", raw or "")
    if not digits:
        return ""
    if digits.startswith("00"):
        digits = digits[2:]
    elif digits.startswith("0"):
        digits = (default_country or "") + digits[1:]
    return digits if 9 <= len(digits) <= 15 else ""


def valid_phone(raw, default_country="263"):
    return bool(normalize_phone(raw, default_country))


def chat_link(phone, text):
    """wa.me link that opens WhatsApp with the message ready to send (no API needed)."""
    from urllib.parse import quote
    return f"https://wa.me/{phone}?text={quote(text)}"


# ---------------------------------------------------------------- errors
def _friendly(code, message, status):
    code = int(code) if str(code).isdigit() else 0
    if code in (190, 102) or status == 401:
        return ("WhatsApp rejected the access token. It has probably expired: create a permanent System User token "
                "in Meta Business Settings and update WHATSAPP_TOKEN.")
    if code == 131030:
        return ("This number is not on your WhatsApp test list. While the WhatsApp setup is in test mode you can only "
                "message numbers added under 'To' in the Meta API Setup page.")
    if code == 131047:
        return ("WhatsApp only allows this message inside 24 hours of the customer's last message. Set up an approved "
                "message template (WHATSAPP_TEMPLATE_QUOTATION / WHATSAPP_TEMPLATE_RECEIPT) to message customers first.")
    if code in (132000, 132001, 132005, 132007, 132012, 132015, 132016):
        return ("WhatsApp does not accept the message template. Check that the template name and language code "
                "(WHATSAPP_TEMPLATE_LANG) match an APPROVED template, and that it has a PDF document header "
                f"and the right number of body variables. ({message})")
    if code in (131026, 1013):
        return "That number is not on WhatsApp, or cannot receive messages. Check the number and try again."
    if code == 131042:
        return "The business's WhatsApp account has a payment problem. Add a payment method in Meta Business settings."
    if code in (130429, 131056, 80007):
        return "WhatsApp is limiting how fast messages are sent. Wait a minute and try again."
    if code in (100, 131009):
        return f"WhatsApp did not accept the request: {message}"
    return f"WhatsApp replied with an error: {message or 'unknown error'}" + (f" (code {code})" if code else "")


def _error_from(resp):
    try:
        err = resp.json().get("error", {})
    except ValueError:
        err = {}
    detail = err.get("error_data", {}).get("details") or err.get("message") or resp.text[:200]
    return _friendly(err.get("code", 0), detail, resp.status_code)


# ---------------------------------------------------------------- sending
def _upload_pdf(cfg, pdf_bytes, filename):
    url = f"{GRAPH}/{cfg['WHATSAPP_API_VERSION']}/{cfg['WHATSAPP_PHONE_NUMBER_ID']}/media"
    resp = requests.post(
        url, headers={"Authorization": f"Bearer {cfg['WHATSAPP_TOKEN']}"},
        data={"messaging_product": "whatsapp", "type": "application/pdf"},
        files={"file": (filename, pdf_bytes, "application/pdf")}, timeout=cfg.get("WHATSAPP_TIMEOUT", 30))
    if resp.status_code >= 400:
        raise RuntimeError(_error_from(resp))
    media_id = resp.json().get("id")
    if not media_id:
        raise RuntimeError("WhatsApp did not accept the PDF upload.")
    return media_id


def send_document(cfg, phone, pdf_bytes, filename, kind, body_values, caption=""):
    """
    Upload the PDF and send it. body_values: the template's {{1}}, {{2}}, ... in order (strings).
    Returns (ok, message).
    """
    if not enabled(cfg):
        return False, "WhatsApp sending is not set up yet."
    if not phone:
        return False, "Enter a valid WhatsApp number for the customer."
    try:
        media_id = _upload_pdf(cfg, pdf_bytes, filename)
        template = template_for(cfg, kind)
        if template:
            payload = {
                "messaging_product": "whatsapp", "to": phone, "type": "template",
                "template": {
                    "name": template, "language": {"code": cfg.get("WHATSAPP_TEMPLATE_LANG") or "en"},
                    "components": [
                        {"type": "header", "parameters": [
                            {"type": "document", "document": {"id": media_id, "filename": filename}}]},
                        {"type": "body", "parameters": [{"type": "text", "text": str(v)[:1000]} for v in body_values]},
                    ],
                },
            }
        else:
            payload = {"messaging_product": "whatsapp", "to": phone, "type": "document",
                       "document": {"id": media_id, "filename": filename, "caption": caption[:1000]}}
        url = f"{GRAPH}/{cfg['WHATSAPP_API_VERSION']}/{cfg['WHATSAPP_PHONE_NUMBER_ID']}/messages"
        resp = requests.post(url, json=payload, headers={"Authorization": f"Bearer {cfg['WHATSAPP_TOKEN']}"},
                             timeout=cfg.get("WHATSAPP_TIMEOUT", 30))
        if resp.status_code >= 400:
            raise RuntimeError(_error_from(resp))
    except RuntimeError as exc:
        log.warning("WhatsApp to %s failed: %s", phone, exc)
        return False, str(exc)
    except requests.RequestException as exc:
        log.warning("WhatsApp to %s could not connect: %s", phone, exc)
        return False, "Could not reach WhatsApp. Check the server's internet connection and try again."
    return True, f"Sent on WhatsApp to +{phone}."

